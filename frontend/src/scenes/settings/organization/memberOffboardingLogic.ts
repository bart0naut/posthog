export const memberOffboardingLogic = kea<memberOffboardingLogicType>([
    path(['scenes', 'settings', 'organization', 'memberOffboardingLogic']),
    connect({
        values: [organizationLogic, ['currentOrganization'], userLogic, ['user']],
        actions: [membersLogic, ['loadMemberScopedApiKeys', 'postRemoveMember', 'loadAllMembers']],
    }),
    actions({
        open: (member: OrganizationMemberType) => ({ member }),
        close: true,
        setKeep: (id: string, keep: boolean) => ({ id, keep }),
        disableAll: (disable: boolean) => ({ disable }),
        disableAllSubscriptions: (disable: boolean) => ({ disable }),
        next: true,
        back: true,
        setKeptResources: (ids: string[]) => ({ ids }),
        loadResources: true,
        remove: true,
    }),
    reducers({
        step: [
            'dashboards' as 'dashboards' | 'subscriptions',
            {
                open: () => 'dashboards' as const,
                next: () => 'subscriptions' as const,
                back: () => 'dashboards' as const,
            },
        ],
        member: [null as OrganizationMemberType | null, { open: (_, { member }) => member, close: () => null }],
        keep: [
            [] as string[],
            {
                open: () => [],
                setKeptResources: (_, { ids }) => ids,
                setKeep: (state, { id, keep }) =>
                    keep ? [...state.filter((item) => item !== id), id] : state.filter((item) => item !== id),
            },
        ],
        loadError: [
            null as string | null,
            { open: () => null, loadResources: () => null, loadResourcesFailure: (_, { error }) => error },
        ],
    }),
    loaders(({ values, actions }) => ({
        resources: {
            __default: null as MemberOffboardingResourceApi[] | null,
            loadResources: async (_, breakpoint) => {
                const member = values.member
                if (!member) {
                    return null
                }
                const resources = await membersOffboardingRetrieve(
                    values.currentOrganization?.id ?? '@current',
                    member.user.uuid
                )
                breakpoint()
                return resources
            },
        },
        removed: {
            __default: false,
            remove: async () => {
                if (
                    !values.member ||
                    values.resourcesLoading ||
                    values.loadError ||
                    values.resources === null ||
                    values.needsSubscriptionReview
                ) {
                    return false
                }
                const member = values.member
                await membersOffboardCreate(values.currentOrganization?.id ?? '@current', member.user.uuid, {
                    keep: values.keep,
                })
                lemonToast.success(`Removed ${fullNameOrEmail(member.user)} from organization`)
                actions.close()
                actions.postRemoveMember(member.user.uuid)
                if (member.user.uuid !== values.user?.uuid) {
                    actions.loadAllMembers()
                }
                return true
            },
        },
    })),
    selectors({
        dashboards: [
            (s) => [s.resources],
            (resources: MemberOffboardingResourceApi[] | null) =>
                resources?.filter((resource) => resource.kind === 'dashboard') ?? [],
        ],
        subscriptions: [
            (s) => [s.resources],
            (resources: MemberOffboardingResourceApi[] | null) =>
                resources?.filter((resource) => resource.kind === 'subscription') ?? [],
        ],
        needsSubscriptionReview: [
            (s) => [s.subscriptions, s.step],
            (subscriptions, step: 'dashboards' | 'subscriptions') => subscriptions.length > 0 && step === 'dashboards',
        ],
    }),
    listeners(({ actions, values }) => ({
        disableAll: ({ disable }) => {
            const other = values.keep.filter((id) => !values.dashboards.some((resource) => resource.id === id))
            actions.setKeptResources([...other, ...(disable ? [] : values.dashboards.map((resource) => resource.id))])
        },
        disableAllSubscriptions: ({ disable }) => {
            const other = values.keep.filter((id) => !values.subscriptions.some((resource) => resource.id === id))
            actions.setKeptResources([
                ...other,
                ...(disable ? [] : values.subscriptions.map((resource) => resource.id)),
            ])
        },
        open: ({ member }) => {
            actions.loadMemberScopedApiKeys(member)
            actions.loadResources()
        },
    })),
])
