export const explainChartLogic: LogicWrapper<explainChartLogicType> = kea<explainChartLogicType>([
    props({} as InsightLogicProps),
    key(keyForInsightLogicProps('new')),
    path((key) => ['products', 'product_analytics', 'insights', 'explainChart', 'explainChartLogic', key]),
    connect((props: InsightLogicProps) => ({
        values: [
            featureFlagLogic,
            ['featureFlags'],
            insightLogic(props),
            ['insight'],
            insightVizDataLogic(props),
            ['insightDataLoading', 'querySource'],
            aiConsentLogic,
            ['dataProcessingAccepted'],
            teamLogic,
            ['baseCurrency'],
            trendsDataLogic(props),
            [
                'display',
                'getTrendsHidden',
                'incompletenessOffsetFromEnd',
                'indexedResults',
                'interval',
                'isTrends',
                'trendsFilter',
            ],
        ],
        actions: [insightVizDataLogic(props), ['loadDataSuccess']],
    })),
    actions({
        openExplain: true,
        closeExplain: true,
    }),
    loaders(({ cache, values }) => ({
        evidenceResults: [
            null as EvidenceResults | null,
            {
                loadEvidence: async (_: void, breakpoint): Promise<EvidenceResults | null> => {
                    const queries = values.evidenceQueries
                    const kinds = new Set(values.moments.map((moment) => moment.kind))
                    // Only a peak, a dip or a change of level reads the splits, and only a peak reads the people count.
                    if (!queries || ![...kinds].some((kind) => kind !== 'latest')) {
                        return null
                    }
                    // A new search, a closed walkthrough or leaving the insight stops the queries of the last search.
                    const abortController = new AbortController()
                    cache.disposables.add(() => () => abortController.abort(), 'explainEvidence', {
                        pauseOnPageHidden: false,
                    })
                    const options = { signal: abortController.signal }
                    // A split that fails leaves the others to explain the change.
                    const [breakdowns, people] = await Promise.all([
                        Promise.all(
                            queries.breakdowns.map(async ({ property, query }) => {
                                try {
                                    const response = await performQuery(query, options)
                                    return { property, query, rows: (response.results ?? []) as EvidenceRow[] }
                                } catch {
                                    return null
                                }
                            })
                        ),
                        queries.people && kinds.has('peak')
                            ? performQuery(queries.people, options)
                                  .then((response) => ({
                                      query: queries.people as NonNullable<EvidenceQueries['people']>,
                                      data: ((response.results?.[0] as EvidenceRow | undefined)?.data ??
                                          []) as number[],
                                  }))
                                  .catch(() => null)
                            : null,
                    ])
                    breakpoint()
                    return {
                        breakdowns: breakdowns.filter(
                            (breakdown): breakdown is NonNullable<typeof breakdown> => !!breakdown
                        ),
                        people,
                    }
                },
            },
        ],
        storyReadingRun: [
            null as StoryReadingRun | null,
            {
                loadStoryReadingRun: async (_: void, breakpoint): Promise<StoryReadingRun | null> => {
                    const series = values.storySeries
                    const facts = values.momentFacts
                    if (!series || !facts.length || !values.dataProcessingAccepted) {
                        return null
                    }
                    let reading: InsightStoryApi | null = null
                    try {
                        reading = await insightsStoryCreate(String(getCurrentTeamId()), {
                            series_label: series.label.slice(0, 200) || 'Series',
                            insight_name: (values.insight.name || values.insight.derived_name || '').slice(0, 400),
                            chapters: facts.slice(0, 8).map(({ moment, facts, evidence }) => ({
                                id: moment.id,
                                title: moment.title.slice(0, 200),
                                summary: plainStoryText(facts).slice(0, 600),
                                evidence: evidence.slice(0, 6).map((item) => plainStoryText(item.text).slice(0, 600)),
                            })),
                        })
                    } catch {
                        reading = null
                    }
                    breakpoint()
                    // A reading made from the facts of an older chart does not belong to this one.
                    if (values.momentFacts !== facts) {
                        return null
                    }
                    return reading ? { ok: true, reading } : { ok: false }
                },
            },
        ],
    })),
    reducers({
        explainOpen: [
            false,
            {
                openExplain: () => true,
                closeExplain: () => false,
            },
        ],
        // A reading belongs to the facts it was made from, and new evidence means new facts.
        storyReadingRun: {
            loadEvidence: () => null,
        },
    }),
    selectors({
        formatValue: [
            (s) => [s.trendsFilter, s.baseCurrency],
            (trendsFilter: TrendsFilter | null | undefined, baseCurrency: teamLogicValues['baseCurrency']) =>
                (value: number): string =>
                    formatAggregationAxisValue(trendsFilter, value, baseCurrency),
        ],
        storySeries: [
            (s) => [s.indexedResults, s.getTrendsHidden, s.display, s.isTrends],
            (
                indexedResults: IndexedTrendResult[],
                getTrendsHidden: trendsDataLogicValues['getTrendsHidden'],
                display: ChartDisplayType | null | undefined,
                isTrends: boolean
            ): StorySeries | null => {
                // A cumulative line shows running totals, which the moments would read as growth every day.
                if (
                    !isTrends ||
                    (display &&
                        (NON_TIME_SERIES_DISPLAY_TYPES.includes(display) ||
                            display === ChartDisplayType.ActionsLineGraphCumulative))
                ) {
                    return null
                }
                const shown = (indexedResults ?? []).filter(
                    (result) => result.compare_label !== 'previous' && !getTrendsHidden(result) && !!result.days?.length
                )
                if (!shown.length) {
                    return null
                }
                // The walkthrough follows the biggest series on the chart.
                const sum = (result: IndexedTrendResult): number =>
                    result.data.reduce((total, value) => total + value, 0)
                const lead = shown.reduce((best, result) => (sum(result) > sum(best) ? result : best))
                return {
                    index: lead.id,
                    label: lead.action?.custom_name || lead.label,
                    queryIndex: lead.action?.order ?? 0,
                    data: lead.data,
                    days: lead.days,
                }
            },
        ],
        moments: [
            (s) => [s.storySeries, s.interval, s.incompletenessOffsetFromEnd],
            (
                storySeries: StorySeries | null,
                interval: IntervalType | null | undefined,
                incompletenessOffsetFromEnd: number
            ): ChartMoment[] =>
                storySeries
                    ? findChartMoments(storySeries, {
                          interval: interval ?? 'day',
                          incompletePoints: -incompletenessOffsetFromEnd,
                      })
                    : [],
        ],
        explainAvailable: [
            (s) => [s.featureFlags, s.moments],
            (featureFlags: FeatureFlagsSet, moments: ChartMoment[]): boolean =>
                !!featureFlags[FEATURE_FLAGS.EXPLAIN_CHART] && moments.length > 0,
        ],
        evidenceQueries: [
            (s) => [s.querySource, s.storySeries],
            (
                querySource: insightVizDataLogicValues['querySource'],
                storySeries: StorySeries | null
            ): EvidenceQueries | null =>
                storySeries ? buildEvidenceQueries(querySource, storySeries.queryIndex) : null,
        ],
        momentFacts: [
            (s) => [
                s.moments,
                s.storySeries,
                s.evidenceResults,
                s.interval,
                s.incompletenessOffsetFromEnd,
                s.formatValue,
            ],
            (
                moments: ChartMoment[],
                storySeries: StorySeries | null,
                evidenceResults: EvidenceResults | null,
                interval: IntervalType | null | undefined,
                incompletenessOffsetFromEnd: number,
                formatValue: (value: number) => string
            ): MomentFacts[] =>
                storySeries
                    ? moments.map((moment) => ({
                          moment,
                          // The same facts the walkthrough shows, so the model reads what the person reads.
                          facts: chapterFacts(storySeries.data, storySeries.days, moment.range, {
                              interval: interval ?? 'day',
                              lastPointInProgress: incompletenessOffsetFromEnd < 0,
                              formatValue,
                          }),
                          evidence: evidenceResults
                              ? evidenceForMoment(moment, evidenceResults, {
                                    values: storySeries.data,
                                    completePoints: storySeries.data.length + incompletenessOffsetFromEnd,
                                    interval: interval ?? 'day',
                                    formatValue,
                                })
                              : [],
                      }))
                    : [],
        ],
        headline: [
            (s) => [s.storyReadingRun, s.storyReadingRunLoading, s.evidenceResultsLoading, s.dataProcessingAccepted],
            (
                storyReadingRun: StoryReadingRun | null,
                storyReadingRunLoading: boolean,
                evidenceResultsLoading: boolean,
                dataProcessingAccepted: boolean
            ): string => {
                const headline = storyReadingRun?.ok ? storyReadingRun.reading.headline.trim() : ''
                if (headline) {
                    // The model sometimes leaves the full stop off.
                    return /[.!?]$/.test(headline) ? headline : `${headline}.`
                }
                if (dataProcessingAccepted && (storyReadingRunLoading || evidenceResultsLoading)) {
                    return 'PostHog AI is reading the chart…'
                }
                return 'Here is what stands out on this chart.'
            },
        ],
        explainChartData: [
            (s) => [
                s.storySeries,
                s.querySource,
                s.indexedResults,
                s.insight,
                s.incompletenessOffsetFromEnd,
                s.headline,
                s.momentFacts,
                s.storyReadingRun,
            ],
            (
                storySeries: StorySeries | null,
                querySource: insightVizDataLogicValues['querySource'],
                indexedResults: IndexedTrendResult[],
                insight: insightLogicValues['insight'],
                incompletenessOffsetFromEnd: number,
                headline: string,
                momentFacts: MomentFacts[],
                storyReadingRun: StoryReadingRun | null
            ): ExplainChartData | null => {
                if (!storySeries || !querySource || !momentFacts.length) {
                    return null
                }
                const readings = storyReadingRun?.ok ? storyReadingRun.reading.chapters : []
                return {
                    query: querySource as unknown as StoryTrendsQuery,
                    results: indexedResults.map(({ label, data, days, action }) => ({
                        label: label ?? undefined,
                        data,
                        days,
                        action: { name: action?.name ?? undefined },
                    })),
                    seriesIndex: storySeries.index,
                    insightName: insight.name || insight.derived_name || null,
                    lastPointInProgress: incompletenessOffsetFromEnd < 0,
                    headline,
                    chapters: momentFacts.map(({ moment, evidence }): StoryChapter => {
                        const cause = readings.find((chapter) => chapter.id === moment.id)?.reading.trim() || null
                        return {
                            title: moment.title,
                            range: moment.range,
                            summary: null,
                            cause: cause && evidence.length ? cause : null,
                            confidence: cause && evidence.length ? confidenceOf(evidence) : null,
                            confidenceReason: null,
                            evidence: evidence.map((item) => ({
                                text: item.text,
                                url: null,
                                query: item.query as Record<string, unknown> | null,
                            })),
                        }
                    }),
                }
            },
        ],
    }),
    listeners(({ actions, cache, values }) => ({
        openExplain: () => {
            posthog.capture('explain chart opened', {
                moments: values.moments.map((moment) => moment.kind),
                can_search_for_cause: !!values.evidenceQueries,
            })
            actions.loadEvidence()
        },
        closeExplain: () => {
            cache.disposables.dispose('explainEvidence')
            posthog.capture('explain chart closed', { chapters: values.moments.length })
        },
        loadDataSuccess: () => {
            if (values.explainOpen) {
                actions.loadEvidence()
            }
        },
        loadEvidenceSuccess: () => {
            if (values.explainOpen) {
                actions.loadStoryReadingRun()
            }
        },
    })),
])
